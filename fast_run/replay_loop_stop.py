"""Replay saved outputs through the stop rules of run_fast.py (no GPU, no model).

Greedy decoding is deterministic, so a fast run produces a prefix of the old output: the
same bytes up to the point where the loop stop or the byte cap would have ended it. This
script cuts every saved raw_output at that point and reports how many generated bytes
would have been saved and which non-truncated rows would get a different parsed answer.
This is how the numbers in fast_run/README.md were obtained.

Usage (from the repository root; any CSV written by run_zero_shot.py / few-shot runs):
    python fast_run/replay_loop_stop.py results/few_shot/ainu/*.csv
    python fast_run/replay_loop_stop.py --max-bytes 1000 --show results/zero_shot/tsez/*.csv
"""
from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import run_fast as f  # noqa: E402


def cut(raw: str) -> tuple[str, str]:
    """Shortest prefix (byte by byte) at which generation would stop, and why."""
    b = raw.encode("utf-8")
    for i in range(1, len(b) + 1):
        t = b[:i].decode("utf-8", "ignore")
        if f.rz.is_complete("all_in_one", t):
            return t, "complete"
        if f._over_cap(t):
            return t, "byte_cap"
        if f._loop(t):
            return t, "loop"
    return raw, "end_of_saved_output"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("files", nargs="+")
    ap.add_argument("--max-bytes", type=int, default=1000)
    ap.add_argument("--show", action="store_true", help="print the rows whose parsed answer changes")
    args = ap.parse_args(argv)
    f.SETTINGS["max_bytes"] = args.max_bytes

    for fn in args.files:
        rows = list(csv.DictReader(open(fn, encoding="utf-8")))
        old = new = changed = 0
        reasons: dict[str, int] = {}
        for r in rows:
            raw = r["raw_output"]
            t, why = cut(raw)
            old += len(raw.encode("utf-8"))
            new += len(t.encode("utf-8"))
            reasons[why] = reasons.get(why, 0) + 1
            # Rows that ended normally before: does the fast run give a different answer?
            if r.get("truncated") != "True" and why != "complete" and f.rz.parse_all_in_one(t) != f.rz.parse_all_in_one(raw):
                changed += 1
                if args.show:
                    print(f"  {r['id']} stopped by {why}; old status {r.get('parse_status')}, {len(raw.encode())} bytes")
                    print("    old:", repr(raw[:160]))
                    print("    tail at stop:", repr(t[-90:]))
        saved = 1 - new / old if old else 0
        print(f"{Path(fn).name}: {len(rows)} rows, generated bytes {old} -> {new} (saved {saved:.0%}), "
              f"stop points {reasons}, normal rows whose parsed answer changes: {changed}")


if __name__ == "__main__":
    main()
