"""Faster zero-shot / few-shot runs: the same runner, with three speed-ups.

This wraps zero_shot/run_zero_shot.py without changing it. Prompts, example selection,
parsing, checkpoints (--resume) and output columns are the same. What differs:

1. Loop stop. Generation stops once the end of the output is one piece of text repeated
   at least 3 times over at least 60 characters (e.g. "I don't know my origins , "
   three times). In the Ainu 3-shot run, 11% of rows looped and produced about 72% of
   all generated bytes.
2. Byte cap. Generation stops after --max-bytes bytes of output (default 1000). The old
   limit, max_new_tokens = 768, is not counted in bytes by Bolmo's generate: looping
   rows reached about 2,000 bytes. The longest gold answer (transliteration line +
   gloss line) is 819 bytes in Ainu test, 677 in Tsez, 454 in Jejueo.
3. Precision. --dtype auto loads the model in bfloat16 on GPUs that support it natively
   (A100, L4; compute capability 8 or higher) and in float32 elsewhere (T4), like the
   LoRA code. float32 is what all earlier runs used.

Rows stopped by 1 or 2 are marked truncated = True, as before. A new column
stop_reason says why each output ended: complete | loop | byte_cap | max_new_tokens | eos.
The speed-up settings are written into the run's generation settings, so they appear in
the .meta.json and in the --resume signature.

Results go to results/fast_run/<lang>/ by default, never over the original results.

Usage (from the repository root, on Colab):
    python fast_run/run_fast.py --lang ainu --split dev --limit 10            # smoke test
    python fast_run/run_fast.py --lang ainu --split test --shots 3 --resume   # full run
All other options are those of zero_shot/run_zero_shot.py (--strategy, --limit, ...).
"""
from __future__ import annotations

import argparse
import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "zero_shot"))
import run_zero_shot as rz  # noqa: E402

# Set by main() before the model is loaded.
SETTINGS = {"max_bytes": 1000, "loop_stop": True, "loop_min_span": 60, "loop_min_reps": 3,
            "loop_max_period": 200, "dtype": "float32"}


# ----------------------------------------------------------------------------- stop rules


def loop_detected(text: str, min_span: int = 60, min_reps: int = 3, max_period: int = 200) -> bool:
    """True if the end of text is one unit of 1..max_period characters repeated at least
    min_reps times, covering at least min_span characters."""
    n = len(text)
    for p in range(1, min(max_period, n // min_reps) + 1):
        reps = max(min_reps, -(-min_span // p))
        if p * reps > n:
            continue
        if text[n - p * reps:] == text[n - p:] * reps:
            return True
    return False


def _loop(text: str) -> bool:
    s = SETTINGS
    return s["loop_stop"] and loop_detected(text, s["loop_min_span"], s["loop_min_reps"], s["loop_max_period"])


def _over_cap(text: str) -> bool:
    return len(text.encode("utf-8")) >= SETTINGS["max_bytes"]


def stop_reason(kind: str, text: str, n_new: int, max_new_tokens: int) -> str:
    if rz.is_complete(kind, text):
        return "complete"
    if _loop(text):
        return "loop"
    if _over_cap(text):
        return "byte_cap"
    if n_new >= max_new_tokens - 1:  # Bolmo stops at budget - 1
        return "max_new_tokens"
    return "eos"


# ----------------------------------------------------------------------------- generator


class FastGenerator(rz.Generator):
    def __init__(self, model_id: str, revision: str, max_new_tokens: int, device: str | None = None):
        rz.check_dependencies()
        import torch
        from transformers import AutoModelForCausalLM, AutoTokenizer, StoppingCriteria

        self.torch = torch
        self.device = device or ("cuda" if torch.cuda.is_available() else "cpu")
        dtype = {"float32": torch.float32, "bfloat16": torch.bfloat16}[SETTINGS["dtype"]]
        self.tokenizer = AutoTokenizer.from_pretrained(model_id, revision=revision, trust_remote_code=True)
        self.model = AutoModelForCausalLM.from_pretrained(
            model_id, revision=revision, trust_remote_code=True, torch_dtype=dtype
        ).to(self.device)
        self.model.eval()
        print(f"Model loaded in {self.model.dtype}", flush=True)
        self.max_new_tokens = max_new_tokens
        self.use_stopping = True
        self._StoppingCriteria = StoppingCriteria

    def _stopper(self, kind: str, prompt_ids: list[int]):
        gen = self

        class _Stop(self._StoppingCriteria):
            def __call__(self, input_ids, scores, **kwargs):
                text = gen._decode(rz.generated_part(input_ids[0].tolist(), prompt_ids))
                done = rz.is_complete(kind, text) or _over_cap(text) or _loop(text)
                return gen.torch.tensor([done], dtype=gen.torch.bool, device=input_ids.device)

        return _Stop()

    def complete(self, prompt: str, kind: str) -> tuple[str, int, bool]:
        text, n_new, _ = super().complete(prompt, kind)
        reason = stop_reason(kind, text, n_new, self.max_new_tokens)
        return text, n_new, reason in ("loop", "byte_cap", "max_new_tokens")


# ----------------------------------------------------------------------------- outputs

_write_outputs = rz.write_outputs


def write_outputs(records: list[dict], out_csv: Path, meta: dict) -> None:
    """Adds stop_reason per row and its counts to the metadata, then writes as usual."""
    budget = meta["generation"]["max_new_tokens"]
    for r in records:
        if "raw_output" in r:
            r["stop_reason"] = stop_reason("all_in_one", r["raw_output"], int(r["n_new_tokens"]), budget)
        else:  # two_stage
            for k in ("1", "2"):
                r[f"stop_reason_step{k}"] = stop_reason("single", r[f"raw_output_step{k}"],
                                                        int(r[f"n_new_tokens_step{k}"]), budget)
    counts: dict[str, int] = {}
    for r in records:
        for k, v in r.items():
            if k.startswith("stop_reason"):
                counts[v] = counts.get(v, 0) + 1
    gold_bytes = [len((r["gold_transliteration"] + "\nGloss: " + r["gold_gloss"]).encode("utf-8"))
                  for r in records]
    meta = {**meta, "stop_reason_counts": counts,
            "gold_answer_bytes_max": max(gold_bytes) if gold_bytes else None,
            "rows_with_gold_answer_over_max_bytes": sum(b >= SETTINGS["max_bytes"] for b in gold_bytes),
            "runner": "fast_run/run_fast.py (wraps zero_shot/run_zero_shot.py)"}
    if meta["rows_with_gold_answer_over_max_bytes"]:
        print(f"[warn] {meta['rows_with_gold_answer_over_max_bytes']} gold answers are longer than "
              f"--max-bytes {SETTINGS['max_bytes']}; consider a larger cap for this language.")
    _write_outputs(records, out_csv, meta)


# ----------------------------------------------------------------------------- main


def resolve_dtype(choice: str) -> str:
    if choice != "auto":
        return choice
    import torch
    if torch.cuda.is_available() and torch.cuda.get_device_capability()[0] >= 8:
        return "bfloat16"  # A100 / L4
    return "float32"       # T4 / CPU: no native bf16


def main(argv: list[str] | None = None) -> list[Path]:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--max-bytes", type=int, default=1000, help="stop after this many output bytes (default 1000)")
    ap.add_argument("--no-loop-stop", action="store_true", help="turn the loop stop off")
    ap.add_argument("--dtype", choices=["auto", "float32", "bfloat16"], default="auto",
                    help="auto = bfloat16 on A100/L4, float32 on T4 (default auto)")
    ap.add_argument("--lang", default="korean")
    ap.add_argument("--out-dir", default=None, help="default: results/fast_run/<lang>")
    args, rest = ap.parse_known_args(argv)

    SETTINGS.update(max_bytes=args.max_bytes, loop_stop=not args.no_loop_stop, dtype=resolve_dtype(args.dtype))
    print(f"Speed-ups: {SETTINGS}", flush=True)

    # Same config, with the speed-up settings added to 'generation' (meta + resume signature).
    cfg = json.loads(rz.CONFIG_PATH.read_text(encoding="utf-8"))
    cfg["generation"]["speedup"] = dict(SETTINGS)
    tmp = Path(tempfile.mkdtemp()) / "zero_shot_fast.json"
    tmp.write_text(json.dumps(cfg, indent=2, ensure_ascii=False), encoding="utf-8")
    rz.CONFIG_PATH = tmp
    rz.Generator = FastGenerator
    rz.write_outputs = write_outputs

    out_dir = args.out_dir or str(ROOT / "results" / "fast_run" / args.lang)
    return rz.main(["--lang", args.lang, "--out-dir", out_dir, *rest])


if __name__ == "__main__":
    main()
